#!/usr/bin/env python3
"""Generate LVGL 9 RGB565 assets from a 2x2 mascot sprite sheet.

Usage:
    python3 tools/make_mascot_assets.py sheet.png firmware/voice/main

The sheet must have four poses of the same character on pure black:
top-left idle, top-right listening, bottom-left thinking, bottom-right
speaking. Characters are located by their bright pixels (a fixed quadrant crop
would clip fins that cross the mid-line), scaled by a common factor, and
written as C arrays with `lv_image_dsc_t` descriptors (RGB565, no alpha).

Requires Pillow (system python3 usually has it).
"""

import pathlib
import sys

from PIL import Image

SIZE = 240
NAMES = ("idle", "listening", "thinking", "speaking")
THRESHOLD = 24
PADDING = 1.12


def widest_gap(proj: list[int], lo: int, hi: int) -> tuple[int, int]:
    """Return (length, start) of the widest empty run in proj[lo:hi]."""
    best = (0, lo)
    run_start = None
    for i in range(lo, hi):
        if proj[i] == 0:
            if run_start is None:
                run_start = i
        elif run_start is not None:
            if i - run_start > best[0]:
                best = (i - run_start, run_start)
            run_start = None
    if run_start is not None and hi - run_start > best[0]:
        best = (hi - run_start, run_start)
    return best


def find_regions(img: Image.Image):
    w, h = img.size
    px = img.load()
    col = [0] * w
    row = [0] * h
    for y in range(h):
        for x in range(w):
            if max(px[x, y]) > THRESHOLD:
                col[x] += 1
                row[y] += 1

    _, vx = widest_gap(col, int(w * 0.3), int(w * 0.7))
    vlen = widest_gap(col, int(w * 0.3), int(w * 0.7))[0]
    split_x = vx + vlen // 2
    hlen, hy = widest_gap(row, int(h * 0.3), int(h * 0.7))
    split_y = hy + hlen // 2

    regions = [
        (0, 0, split_x, split_y),
        (split_x, 0, w, split_y),
        (0, split_y, split_x, h),
        (split_x, split_y, w, h),
    ]

    boxes = []
    for x0, y0, x1, y1 in regions:
        xs = [x for x in range(x0, x1) if col[x] > 0]
        ys = [y for y in range(y0, y1) if row[y] > 0]
        boxes.append((min(xs), min(ys), max(xs), max(ys)))
    return boxes


def to_rgb565(img: Image.Image) -> bytes:
    img = img.convert("RGB")
    px = img.load()
    out = bytearray()
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b = px[x, y]
            # Snap near-black compression noise to true black so the sprite
            # corners disappear into the black UI background.
            if r < 10 and g < 10 and b < 10:
                r = g = b = 0
            v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
            out += bytes((v & 0xFF, v >> 8))
    return bytes(out)


def emit(name: str, data: bytes, out_dir: pathlib.Path) -> None:
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    body = "\n".join(rows)

    (out_dir / f"mascot_{name}.c").write_text(
        f'''/* Generated by tools/make_mascot_assets.py. Do not edit by hand. */
#include "mascot.h"

static const uint8_t mascot_{name}_map[] = {{
{body}
}};

const lv_image_dsc_t mascot_{name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565,
        .flags = 0,
        .w = {SIZE},
        .h = {SIZE},
        .stride = {SIZE * 2},
    }},
    .data_size = sizeof(mascot_{name}_map),
    .data = mascot_{name}_map,
}};
'''
    )


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2

    sheet = Image.open(sys.argv[1]).convert("RGB")
    out_dir = pathlib.Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    print("sheet:", sheet.size)

    boxes = find_regions(sheet)
    largest = max(max(x1 - x0, y1 - y0) for x0, y0, x1, y1 in boxes)
    side = int(largest * PADDING)

    for name, box in zip(NAMES, boxes):
        x0, y0, x1, y1 = box
        cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
        tile = Image.new("RGB", (side, side), (0, 0, 0))
        tile.paste(sheet.crop(box), (side // 2 - (x1 - x0) // 2,
                                     side // 2 - (y1 - y0) // 2))
        tile = tile.resize((SIZE, SIZE), Image.LANCZOS)
        emit(name, to_rgb565(tile), out_dir)
        print("wrote", name, "from", box)

    (out_dir / "mascot.h").write_text(
        '''#pragma once

#include "lvgl.h"

/* Four mascot poses, 240x240, RGB565 on black. */
extern const lv_image_dsc_t mascot_idle;
extern const lv_image_dsc_t mascot_listening;
extern const lv_image_dsc_t mascot_thinking;
extern const lv_image_dsc_t mascot_speaking;
'''
    )
    print("wrote mascot assets to", out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
